const { _electron: electron } = require('playwright')
const path = require('node:path')
const fs = require('node:fs/promises')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
const artifactDir = path.resolve(process.env.LEXICON_ARTIFACT_DIR || path.join(root, 'verification'))
const dataDir = path.join(artifactDir, 'test-profile-' + Date.now())
const report = { checks: [], errors: [], screenshots: [] }
let app, page
const check = (name, detail) => report.checks.push({ name, detail, passed: true })
const nav = async name => { await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name, exact: true }).click() }
const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('lexicon-state-v1')))
async function launch() {
  app = await electron.launch({ executablePath: process.env.LEXICON_EXE || undefined, args: process.env.LEXICON_EXE ? [] : [root], env: { ...process.env, LEXICON_TEST_DATA: dataDir, ELECTRON_ENABLE_LOGGING: '1' }, timeout: 30000 })
  page = await app.firstWindow()
  page.on('pageerror', e => report.errors.push(e.message))
  await page.getByRole('navigation', { name: '主导航' }).waitFor()
  await page.evaluate(() => localStorage.setItem('lexicon-tour-done-v1', '1'))
}
async function screenshot(name) { const f = path.join(artifactDir, name + '.png'); await page.waitForTimeout(350); await page.screenshot({ path: f, fullPage: true, animations: 'disabled' }); report.screenshots.push(f) }
async function addWord(text, gloss) {
  await page.getByRole('button', { name: '录入单词', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('英文单词', { exact: true }).fill(text)
  await dialog.getByLabel('中文释义', { exact: true }).fill(gloss)
  await dialog.getByRole('button', { name: '保存单词', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
}
